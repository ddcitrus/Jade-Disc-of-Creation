/**
 * 角色属性合计。
 * @param {object} character 角色档案（origin / race / traits / alloc）
 * @param {object} [opts]
 * @param {boolean} [opts.excludeTraits] 生成角色快照时传 true：快照里的「自身」值不含特质，
 *   特质与装备一样由系统实时叠加（见 snapshotSchema.js 的 attrRows 三段口径）。
 *   建号界面 / 侧栏等展示「角色总属性」的场合不传，保持含特质的合计。
 */
export function computeAttrs(character, opts = {}) {
  const final = { ...BASE_ATTRS };
  const add = (mods) => { if (mods) for (const [k, v] of Object.entries(mods)) final[k] = (final[k] || 0) + v; };
  add(character?.origin?.mods);
  add(character?.race?.mods);
  // 特质词条按特质库解析（角色档案里的 mods 可能被历史同步丢过，不能只信它）
  if (!opts.excludeTraits) for (const t of character?.traits || []) add(resolveTraitMods(t));
  for (const [k, v] of Object.entries(character?.alloc || {})) final[k] = (final[k] || 0) + v;
  return final;
}

export function rootDisplayName(root) {
  if (!root) return '未定';
  if (root.typeId === 'none') return '无灵根';
  return `${root.typeName} ${root.elements.join('')}` + (root.typeId === 'custom' && root.customName ? `（${root.customName}）` : '');
}

